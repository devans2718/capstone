#!/usr/bin/env python3
"""Load the knowledge graph's corpus layer straight into Neo4j.

HOW TO RUN (from the repo root, in WSL, with the server up: kg/compose.yaml)
    .venv-app/bin/python kg/build_corpus.py
    Connection from NEO4J_URI / NEO4J_USER / NEO4J_PASSWORD, defaulting to the
    local server in kg/compose.yaml.

WHAT IT BUILDS
    Five levels, each its own node type (pre-registration §3; ai-design-plan):
      Site     one flap: the unit with a /t/ or /d/ label and a fold per
               condition. All 10,392 inventory sites; the 3 clamped excerpts
               carry eligible = false and no folds, as in the run
      Token    one word token, by track and word start. Holds 1 or 2 sites
               (`dated`), which is why the label sits on the Site
      TypeKey  capstone.splits.type_key(): the split's unit, not a lemma
      Lemma    the registered lemma from lemma-overlap-joint-20260926.tsv
      Speaker  linked to the Buckeye Dataset node of the design layer
    Site -IN_TOKEN-> Token -HAS_KEY-> TypeKey, Token -HAS_LEMMA-> Lemma,
    Token -SPOKEN_BY-> Speaker -IN_DATASET-> Dataset.

    The lemma hangs off the Token, not the TypeKey, because it was assigned
    from the word and its part-of-speech tag, and the tag is per token.

    THE LISTENING AUDIT (pre-registration §7)
    The audit sample Artifact -SAMPLES {order, flap, word, clip}-> each of its
    80 Sites. The verdicts (yes / no / cant_tell per question) sit on the edge,
    not the Site: they belong to this one audit, by one untrained listener,
    and a second audit would be a second Artifact with its own edges. Counted
    by capstone.audit.counted_verdicts (last verdict wins, audit lines only)
    from the local review log /data/reviews/reviewed.jsonl; without the log the
    edges are skipped. Refused unless the counts in the graph equal
    capstone.audit.summarize's, the table in results/flapping/audit-20260928.txt.

WHERE THE DATA COMES FROM, AND THE CHECKS THAT IT IS THE RUN'S
    - results/flapping/sites-20260924.parquet, the inventory. Refused unless
      its sha256 is the pilot manifest's inventory_hash.
    - Folds recomputed with capstone.splits over the eligible sites, the
      registered seed for `random`. Refused unless every condition's fold
      sizes equal those recorded in probe-folds-20260926.csv.
    - Lemmas read from the registered TSV rather than re-lemmatized, so a
      different NLTK or WordNet cannot move them.
    - After loading, the lemma overlap under `joint` is recomputed IN THE
      GRAPH, from the fold properties and HAS_LEMMA alone, and compared site
      by site with the TSV. Expected: 2,612 same label + 191 other label only
      + 7,586 unseen = 10,389.

THE BUCKEYE RULE
    Everything this loads is Buckeye-derived, so it writes no file: rows go
    from the inventory to the server over Bolt. Without a registered copy (in
    the public repo, the parquet is regenerated by scripts/count_flap_sites.py)
    there is nothing to load, and the design layer stands on its own.

RELOADING
    Every node carries layer = "corpus", and the script starts by deleting
    exactly those, so it leaves the design layer alone, as build_design.py
    leaves this one.

    ORDER: DESIGN FIRST. IN_DATASET and SAMPLES join the two layers, and
    reloading the design layer detaches its nodes, which drops them. After
    any design reload, run this again.
"""

from __future__ import annotations

import csv
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

import pandas as pd  # noqa: E402
import pyarrow.parquet as pq  # noqa: E402
from neo4j import GraphDatabase  # noqa: E402

from capstone import seeds  # noqa: E402
from capstone.audit import AUDIT_TARGETS, counted_verdicts, summarize  # noqa: E402
from capstone.predictions import file_hash  # noqa: E402
from capstone.splits import CONDITIONS, site_folds, speaker_folds, type_folds, type_key  # noqa: E402

RESULTS = REPO / "results" / "flapping"
INVENTORY = RESULTS / "sites-20260924.parquet"
LEMMAS = RESULTS / "lemma-overlap-joint-20260926.tsv"
FOLDS_CSV = RESULTS / "probe-folds-20260926.csv"
MANIFEST = RESULTS / "run-manifest-pilot.json"
AUDIT_SAMPLE = RESULTS / "audit-sample-20260926.tsv"
REVIEWS = Path("/data/reviews/reviewed.jsonl")
RUN_ID = "pilot-20260926"

URI = os.environ.get("NEO4J_URI", "bolt://localhost:7687")
AUTH = (os.environ.get("NEO4J_USER", "neo4j"),
        os.environ.get("NEO4J_PASSWORD", "phonoprobe-local"))

SAMPLE_RATE = 16_000  # Buckeye's; the inventory's *_sample columns count at it
BATCH = 2_000
EXPECTED = {"same_label": 2_612, "other_label_only": 191, "unseen": 7_586}

# Fold property per condition, on the Site.
FOLD_PROP = {c: f"fold_{c}" for c in CONDITIONS}


def fail(msg: str) -> None:
    sys.exit(f"build_corpus: {msg}")


# ---------------------------------------------------------------------------
# Read and check
# ---------------------------------------------------------------------------

def read_inventory():
    want = json.loads(MANIFEST.read_text())["inventory_hash"]
    if file_hash(INVENTORY) != want:
        fail(f"{INVENTORY.name} does not hash to the pilot run's inventory ({want[:12]})")
    return pq.read_table(INVENTORY).to_pandas()


def assign_folds(inv) -> dict[str, list]:
    """Each condition's fold per site; None for the ineligible ones."""
    elig = ~inv.excerpt_clamped.to_numpy()
    sub = inv[elig]
    folds = {}
    for cond in CONDITIONS:
        f = site_folds(cond, sub.speaker, sub.word, sub.underlying,
                       seed=seeds.FOLDS if cond == "random" else None)
        it = iter(int(x) for x in f)
        folds[cond] = [next(it) if e else None for e in elig]
    return folds


def check_fold_sizes(folds: dict) -> None:
    """Fold sizes against the run's own record of how many sites each probe scored."""
    recorded = {}
    with FOLDS_CSV.open(newline="") as fh:
        for r in csv.DictReader(fh):
            if r["subsampled"] == "False":
                recorded[(r["condition"], int(r["fold"]))] = int(r["n"])
    for cond in CONDITIONS:
        ours = Counter(f for f in folds[cond] if f is not None)
        theirs = {k: n for (c, k), n in recorded.items() if c == cond}
        if dict(ours) != theirs:
            fail(f"{cond} fold sizes differ from {FOLDS_CSV.name}")


def read_lemmas(inv) -> dict[str, dict]:
    with LEMMAS.open(newline="") as fh:
        rows = {r["site_id"]: r for r in csv.DictReader(fh, delimiter="\t")}
    eligible = set(inv.site_id[~inv.excerpt_clamped])
    if set(rows) != eligible:
        fail(f"{LEMMAS.name} does not cover exactly the eligible sites")
    return rows


# ---------------------------------------------------------------------------
# Rows for each node type
# ---------------------------------------------------------------------------

def build_rows(inv, folds: dict, lemmas: dict) -> dict[str, list]:
    elig = ~inv.excerpt_clamped.to_numpy()
    spk_fold = speaker_folds(inv.speaker[elig])
    typ_fold = type_folds(inv.word[elig])

    sites, tokens = [], {}
    for i, r in enumerate(inv.itertuples(index=False)):
        tok = f"token:{r.track}:{r.word_start_sample}"
        lem = lemmas.get(r.site_id, {}).get("lemma")
        t = {"key": tok, "name": r.word, "word": r.word, "track": r.track,
             "start": r.word_start_sample / SAMPLE_RATE,
             "end": r.word_end_sample / SAMPLE_RATE, "pos": r.pos,
             "speaker": f"speaker:{r.speaker}", "type_key": f"typekey:{type_key(r.word)}",
             "lemma": f"lemma:{lem}" if lem else None}
        prev = tokens.get(tok)
        if prev is None:
            tokens[tok] = t
        else:
            # Sites of one token must agree on everything the token holds; a
            # clamped site has no registered lemma, so a sibling's fills it.
            same = {k: v for k, v in t.items() if k != "lemma"}
            if any(prev[k] != v for k, v in same.items()):
                fail(f"sites of {tok} disagree on the word they belong to")
            if t["lemma"] and prev["lemma"] not in (None, t["lemma"]):
                fail(f"sites of {tok} carry different lemmas")
            prev["lemma"] = prev["lemma"] or t["lemma"]

        s = {"key": f"site:{r.site_id}", "name": r.site_id, "site_id": r.site_id,
             "token": tok, "underlying": r.underlying, "start": r.start, "end": r.end,
             "duration_ms": r.duration_ms, "n_frames": int(r.n_frame_onsets),
             "phone_idx_in_word": int(r.phone_idx_in_word),
             "prev_phone": r.prev_phone, "next_phone": r.next_phone,
             "surface_ambiguous": bool(r.surface_ambiguous),
             "annotator_mark": r.annotator_mark or None,
             "eligible": bool(elig[i])}
        for cond in CONDITIONS:
            s[FOLD_PROP[cond]] = folds[cond][i]
        sites.append(s)

    keys = sorted({t["type_key"] for t in tokens.values()})
    return {
        "sites": sites,
        "tokens": list(tokens.values()),
        "type_keys": [{"key": k, "name": k.split(":", 1)[1],
                       "fold": typ_fold.get(k.split(":", 1)[1])} for k in keys],
        "lemmas": [{"key": k, "name": k.split(":", 1)[1]}
                   for k in sorted({t["lemma"] for t in tokens.values() if t["lemma"]})],
        "speakers": [{"key": f"speaker:{c}", "name": c, "fold": spk_fold.get(c)}
                     for c in sorted(set(inv.speaker))],
    }


# ---------------------------------------------------------------------------
# Load
# ---------------------------------------------------------------------------

def none_free(rows: list) -> list:
    """Drop None values so they become absent properties, as in the design layer."""
    return [{k: v for k, v in r.items() if v is not None} for r in rows]


LOAD = {
    "speakers": """
        UNWIND $rows AS r
        MERGE (n:Speaker {key: r.key}) SET n += r, n.layer = 'corpus'
        WITH n
        MATCH (d:Dataset {key: 'ds-buckeye'}) MERGE (n)-[:IN_DATASET]->(d)""",
    "type_keys": """
        UNWIND $rows AS r
        MERGE (n:TypeKey {key: r.key}) SET n += r, n.layer = 'corpus'""",
    "lemmas": """
        UNWIND $rows AS r
        MERGE (n:Lemma {key: r.key}) SET n += r, n.layer = 'corpus'""",
    "tokens": """
        UNWIND $rows AS r
        MERGE (n:Token {key: r.key})
        SET n += apply_props, n.layer = 'corpus'
        WITH n, r
        MATCH (s:Speaker {key: r.speaker}), (k:TypeKey {key: r.type_key})
        MERGE (n)-[:SPOKEN_BY]->(s)
        MERGE (n)-[:HAS_KEY]->(k)
        WITH n, r WHERE r.lemma IS NOT NULL
        MATCH (l:Lemma {key: r.lemma}) MERGE (n)-[:HAS_LEMMA]->(l)""",
    "sites": """
        UNWIND $rows AS r
        MERGE (n:Site {key: r.key})
        SET n += apply_props, n.layer = 'corpus'
        WITH n, r
        MATCH (t:Token {key: r.token}) MERGE (n)-[:IN_TOKEN]->(t)""",
}

# Row fields that become edges, not node properties. `apply_props` in the
# queries above is replaced by a projection of the rest.
EDGE_FIELDS = {"tokens": ("speaker", "type_key", "lemma"), "sites": ("token",)}


def load(driver, rows: dict) -> None:
    for label in ("Site", "Token", "TypeKey", "Lemma", "Speaker"):
        driver.execute_query(f"CREATE CONSTRAINT {label.lower()}_key IF NOT EXISTS "
                             f"FOR (n:{label}) REQUIRE n.key IS UNIQUE")
    with driver.session() as s:
        s.run("MATCH (n) WHERE n.layer = 'corpus' "
              "CALL (n) { DETACH DELETE n } IN TRANSACTIONS OF 5000 ROWS").consume()
    for kind in ("speakers", "type_keys", "lemmas", "tokens", "sites"):
        # Node properties are the row minus its edge fields, as a map projection.
        drop = EDGE_FIELDS.get(kind, ())
        props = "r {" + ", ".join(f".{k}" for k in _node_fields(rows[kind], drop)) + "}"
        query = LOAD[kind].replace("apply_props", props)
        data = none_free(rows[kind])
        for i in range(0, len(data), BATCH):
            driver.execute_query(query, rows=data[i:i + BATCH])


def _node_fields(rows: list, drop: tuple) -> list:
    return sorted({k for r in rows for k in r} - set(drop))


# ---------------------------------------------------------------------------
# The check: the registered lemma overlap, recomputed in the graph
# ---------------------------------------------------------------------------

# A joint test site's probe trains on the sites sharing neither its speaker
# fold nor its type fold. Its lemma is SEEN if a training site's token has the
# same lemma, SAME LABEL if one of those has the test site's own label.
OVERLAP = """
MATCH (s:Site {eligible: true})-[:IN_TOKEN]->(:Token)-[:HAS_LEMMA]->(l:Lemma)
OPTIONAL MATCH (l)<-[:HAS_LEMMA]-(:Token)<-[:IN_TOKEN]-(o:Site {eligible: true})
  WHERE o.fold_speaker_disjoint <> s.fold_speaker_disjoint
    AND o.fold_word_disjoint <> s.fold_word_disjoint
WITH s, collect(DISTINCT o.underlying) AS train_labels
RETURN s.site_id AS site_id, size(train_labels) > 0 AS seen,
       s.underlying IN train_labels AS same_label
"""


def check_overlap(driver, lemmas: dict) -> None:
    recs, _, _ = driver.execute_query(OVERLAP)
    got = {r["site_id"]: (r["seen"], r["same_label"]) for r in recs}
    if set(got) != set(lemmas):
        fail(f"the overlap query reached {len(got)} sites, not the {len(lemmas)} eligible")
    want = {sid: (r["lemma_in_train"] == "true", r["lemma_in_train_same_label"] == "true")
            for sid, r in lemmas.items()}
    differ = [sid for sid in want if got[sid] != want[sid]]
    if differ:
        fail(f"{len(differ)} sites differ from {LEMMAS.name}, e.g. {differ[:3]}")
    tally = Counter("same_label" if same else "other_label_only" if seen else "unseen"
                    for seen, same in got.values())
    print("lemma overlap under joint, recomputed in the graph:")
    for k, n in EXPECTED.items():
        print(f"  {k:<17} {tally[k]:>5}  (registered {n})")
    if dict(tally) != EXPECTED:
        fail("the totals differ from the registered figures")
    print(f"  every site matches {LEMMAS.name}")


# ---------------------------------------------------------------------------
# The listening audit
# ---------------------------------------------------------------------------

SAMPLES = """
UNWIND $rows AS r
MATCH (a:Artifact {key: 'art-audit-sample'}), (s:Site {key: r.site})
MERGE (a)-[e:SAMPLES]->(s)
SET e += r {.order, .flap, .word, .clip}
"""

# Per question and class, as the report counts them.
AUDIT_COUNTS = """
MATCH (:Artifact {key: 'art-audit-sample'})-[e:SAMPLES]->(s:Site)
UNWIND $questions AS q
RETURN q AS question, s.underlying AS class, e[q] AS verdict, count(*) AS n
"""


def load_audit(driver) -> None:
    if not REVIEWS.exists():
        print(f"no {REVIEWS}: audit edges skipped")
        return
    lines = [json.loads(x) for x in REVIEWS.read_text().splitlines() if x.strip()]
    sample = pd.read_csv(AUDIT_SAMPLE, sep="\t")  # as scripts/summarize_audit.py reads it
    got = counted_verdicts(lines, sample, RUN_ID)
    rows = [{"site": f"site:{r.site_id}", "order": int(r.order),
             **{q: got.get((r.site_id, q)) for q in AUDIT_TARGETS}}
            for r in sample.itertuples(index=False)]
    driver.execute_query(SAMPLES, rows=none_free(rows))

    # The check: the graph's counts against capstone.audit.summarize's table.
    recs, _, _ = driver.execute_query(AUDIT_COUNTS, questions=list(AUDIT_TARGETS))
    graph = {(r["question"], r["class"], r["verdict"]): r["n"] for r in recs}
    n_edges = sum(n for (q, _, _), n in graph.items() if q == next(iter(AUDIT_TARGETS)))
    if n_edges != len(sample):
        fail(f"{n_edges} SAMPLES edges for {len(sample)} sampled sites")
    for r in summarize(lines, sample, RUN_ID).to_dict("records"):
        cls = r["class"].strip("/")  # the report's class is "/t/"; the Site's is "t"
        for v in ("yes", "no", "cant_tell"):
            n = graph.get((r["question"], cls, v), 0)
            if n != r[v]:
                fail(f"audit {r['question']} /{cls}/ {v}: graph {n}, report {r[v]}")
    print(f"audit: {n_edges} SAMPLES edges; counts match the audit report")


def main() -> None:
    inv = read_inventory()
    folds = assign_folds(inv)
    check_fold_sizes(folds)
    lemmas = read_lemmas(inv)
    rows = build_rows(inv, folds, lemmas)

    with GraphDatabase.driver(URI, auth=AUTH) as driver:
        driver.verify_connectivity()
        load(driver, rows)
        counts, _, _ = driver.execute_query(
            "MATCH (n {layer: 'corpus'}) RETURN labels(n)[0] AS label, count(*) AS n "
            "ORDER BY label")
        print("loaded the corpus layer:")
        for r in counts:
            print(f"  {r['label']:<9} {r['n']}")
        per_token = Counter(Counter(s["token"] for s in rows["sites"]).values())
        print("  sites per token: " + ", ".join(f"{k}: {v}" for k, v in sorted(per_token.items())))
        check_overlap(driver, lemmas)
        load_audit(driver)


if __name__ == "__main__":
    main()

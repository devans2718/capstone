#!/usr/bin/env python3
"""Flapping minimal pairs spoken by Kokoro-82M, from plain text and from forced phonemes.

Challenge 4 AI Design, multimodal. Not part of the registered study: no
Buckeye audio is involved, and nothing here feeds a probe.

HOW TO RUN
    Kokoro needs torch, which .venv-app does not carry, so it runs in its own
    environment, outside the repo:
        uv venv --python 3.12 KOKORO_VENV
        uv pip install --python KOKORO_VENV/bin/python \\
            --index-url https://download.pytorch.org/whl/cpu \\
            --extra-index-url https://pypi.org/simple \\
            --index-strategy unsafe-best-match torch "kokoro>=0.9" soundfile \\
            "en_core_web_sm @ https://github.com/explosion/spacy-models/releases/download/en_core_web_sm-3.8.0/en_core_web_sm-3.8.0-py3-none-any.whl"
        KOKORO_VENV/bin/python -I scripts/speak_flap_pairs.py OUT_DIR ESPEAK_DATA
    The weights (hexgrad/Kokoro-82M, Apache 2.0) download from Hugging Face on
    first use. No sudo: espeak-ng comes bundled with espeakng-loader.

    ESPEAK_DATA is a COPY (not a symlink: phonemizer resolves it) of
    espeakng_loader's espeak-ng-data at a short path. espeak-ng keeps its
    data path in a fixed-size buffer (160 bytes), and a venv's site-packages
    path can overflow it; espeak-ng then falls back to its compiled-in path,
    which is the wheel's build machine, and exits.

WHAT IT MAKES
    Each word in a carrier, "Say ___ again.", in an American voice (af_heart)
    and a British one (bf_emma), as 24 kHz WAVs, plus index.md with the
    phoneme string sent for each clip.
      text      plain text through Kokoro's own G2P (misaki): what the model
                does by itself
      flap      the word's /t/ or /d/ forced to Kokoro's flap token
      stop      (/t/ words, American voice) the flap token forced back to a
                plain [t]

    Kokoro 1.0's flap token is `T`: misaki writes the lexicon's [ɾ] as `T`
    for this model version (misaki/en.py), and `ɾ` itself is in the vocab
    but not what the model was trained on. The American G2P gives /t/ words
    a `T` and leaves /d/ words as `d`; the British G2P gives a plain `t`.
"""

from __future__ import annotations

import sys
from pathlib import Path

import misaki.espeak  # noqa: F401  sets the too-long data path; overridden below
import soundfile as sf
from phonemizer.backend.espeak.wrapper import EspeakWrapper

OUT, ESPEAK_DATA = Path(sys.argv[1]), sys.argv[2]
EspeakWrapper.set_data_path(ESPEAK_DATA)

from kokoro import KPipeline  # noqa: E402

PAIRS = [("writer", "rider"), ("latter", "ladder"), ("metal", "medal")]
VOICES = {"us": ("a", "af_heart"), "gb": ("b", "bf_emma")}
CARRIER = "Say {} again."
FLAP = "T"

# Kokoro's single-letter diphthongs, spelled out for the IPA column.
IPA = {"A": "eɪ", "I": "aɪ", "O": "oʊ", "W": "aʊ", "Y": "ɔɪ", "Q": "əʊ", "T": "ɾ"}


def ipa(ps: str) -> str:
    return "".join(IPA.get(c, c) for c in ps)


def word_phonemes(pipe, word: str) -> str:
    return pipe.g2p(word)[0]


def forced(word_ps: str, underlying: str, to: str) -> str:
    """The word's phonemes with its medial /t/ or /d/ (last one) replaced by `to`."""
    for c in (FLAP, underlying):
        i = word_ps.rfind(c)
        if i > 0:
            return word_ps[:i] + to + word_ps[i + 1:]
    raise SystemExit(f"no {underlying} or {FLAP} in {word_ps}")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for accent, (lang, voice) in VOICES.items():
        pipe = KPipeline(lang_code=lang, repo_id="hexgrad/Kokoro-82M")
        carrier_ps = pipe.g2p(CARRIER.format("X"))[0]
        for pair in PAIRS:
            for word, under in zip(pair, "td"):
                wps = word_phonemes(pipe, word)
                x = pipe.g2p("X")[0]
                variants = {"text": wps, "flap": forced(wps, under, FLAP)}
                if under == "t" and accent == "us":
                    variants["stop"] = forced(wps, under, "t")
                for mode, ps in variants.items():
                    sentence = carrier_ps.replace(x, ps, 1)
                    if mode == "text":
                        audio = [r.audio for r in pipe(CARRIER.format(word), voice=voice)]
                        sent = pipe.g2p(CARRIER.format(word))[0]
                    else:
                        audio = [r.audio for r in pipe.generate_from_tokens(sentence, voice=voice)]
                        sent = sentence
                    name = f"{accent}-{word}-{mode}.wav"
                    sf.write(OUT / name, audio[0].numpy(), 24_000)
                    rows.append((name, accent, voice, word, f"/{under}/", mode, sent, ipa(sent)))
                    print(f"{name:<28} {sent}")

    lines = ["# Kokoro-82M flapping pairs", "",
             "Generated by scripts/speak_flap_pairs.py (capstone repo). Carrier: "
             f"\"{CARRIER.format('___')}\". `T` is Kokoro 1.0's flap token, shown as [ɾ] "
             "in the IPA column; I/A/O/W/Y are its diphthongs.", "",
             "| file | voice | word | underlying | mode | phonemes sent | IPA |",
             "|---|---|---|---|---|---|---|"]
    lines += [f"| {n} | {a} ({v}) | {w} | {u} | {m} | `{s}` | [{i}] |"
              for n, a, v, w, u, m, s, i in rows]
    (OUT / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} clips and index.md to {OUT}")


if __name__ == "__main__":
    main()
